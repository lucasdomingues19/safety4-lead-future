"""Generates src/lms-theme.css: the LMS light and dark themes.

The LMS styles colours inline and with Tailwind arbitrary classes (text-[#69697b] etc.), so the dark theme
maps each colour the LMS uses to a dark-theme equivalent. Re-run after adding new colours:
    python3 scripts/gen-lms-theme.py
"""
import re

def rgb(h):
    h = h.lstrip("#")
    if len(h) == 3: h = "".join(c * 2 for c in h)
    return f"rgb({int(h[0:2],16)}, {int(h[2:4],16)}, {int(h[4:6],16)})"

HOVER_BG, HOVER_TEXT, HOVER_BORDER = "hover\\:bg", "hover\\:text", "hover\\:border"

def tw(prefix, h):  # escaped Tailwind arbitrary class, e.g. .text-\[\#69697b\]
    return f".{prefix}-\\[\\{h}\\]"

# ---- dark palette ----
PAGE, SURFACE, RAISED, ACTIVE = "#0b1230", "#121b3a", "#18224a", "#26335e"
BORDER = "#26325a"

TEXT_DARK = {
    "#0b0b2c": "#eef2ff", "#69697b": "#a9b4cf", "#94a3b8": "#8794b3", "#3434ff": "#a5a9ff",
    "#475569": "#c3cbe0", "#334155": "#c3cbe0", "#4a4a60": "#c3cbe0",
    "#3f6212": "#b5f25a", "#4a5230": "#d4f49a", "#5e7f0f": "#b5f25a", "#8ab815": "#a3e635", "#16a34a": "#6ee7a0",
    "#b91c1c": "#fca5a5", "#c93636": "#fca5a5", "#7f1d1d": "#fecaca", "#be123c": "#fda4af", "#e11d48": "#fda4af",
    "#9a3412": "#fdba74", "#b45309": "#fcd34d", "#c2410c": "#fdba74", "#7a4b00": "#fcd34d", "#a05a00": "#fcd34d",
    "#8a5a00": "#fcd34d", "#7c2d12": "#fdba74",
    "#be185d": "#f9a8d4", "#0a66c2": "#7fb6ff", "#2c23d2": "#a5a0ff",
    "#991b1b": "#fca5a5", "#dc2626": "#fca5a5", "#5555ff": "#a5a9ff",
    "#0f766e": "#5eead4", "#7c3aed": "#c4b5fd", "#0369a1": "#7dd3fc",
}
BLUE_TINT, LIME_TINT, RED_TINT, AMBER_TINT = "rgba(91, 99, 255, 0.16)", "rgba(158, 255, 31, 0.10)", "rgba(244, 63, 94, 0.13)", "rgba(251, 146, 60, 0.13)"
BG_DARK = {"#fff": SURFACE, "#ffffff": SURFACE, "#fafafa": SURFACE, "#eef1f6": PAGE, "#0b0b2c": ACTIVE, "#e2e8f0": BORDER, "#fbfcff": RAISED}
for h in ["#f5f7fa", "#f7f8fc", "#f8fafc", "#fafbfc", "#f1f5f9", "#eef0f6", "#f1f4f8"]: BG_DARK[h] = RAISED
for h in ["#f1f4ff", "#f5f7ff", "#f7f8ff", "#fafbff", "#eef1ff", "#e8ecff", "#eef0ff", "#f3f8ff", "#f1f4fb", "#ece9ff", "#e8e8ff"]: BG_DARK[h] = BLUE_TINT
for h in ["#f4fbe4", "#ecffd1", "#f7fde8", "#e8ffbd", "#fbfdf7", "#f2fcd9"]: BG_DARK[h] = LIME_TINT
for h in ["#fef2f2", "#fff1f2", "#fff5f5", "#fdf2f8", "#fee2e2"]: BG_DARK[h] = RED_TINT
for h in ["#fff7e6", "#fff4e5", "#fff7ed"]: BG_DARK[h] = AMBER_TINT
BORDER_DARK = {}
for h in ["#e2e8f0", "#f1f4f8", "#eef1f6", "#cbd5e1", "#cfd6e4", "#dfe5ee", "#c9d8f0", "#f5f7fa"]: BORDER_DARK[h] = BORDER
for h in ["#c7cdf9", "#dfe3ff"]: BORDER_DARK[h] = "#3b47a8"
for h in ["#d9f09a", "#cde9a0"]: BORDER_DARK[h] = "rgba(158, 255, 31, 0.35)"
for h in ["#fecaca", "#fecdd3", "#ffd6d6"]: BORDER_DARK[h] = "rgba(244, 63, 94, 0.45)"
for h in ["#f5d9a8", "#ffd9a0", "#fed7aa"]: BORDER_DARK[h] = "rgba(251, 146, 60, 0.45)"
LIME_SOLID = ["#9eff1f", "#a6e21a", "#84cc16"]  # navy text stays navy on these

# ---- light theme: the few colours that fail contrast on white ----
TEXT_LIGHT = {"#94a3b8": "#64748b", "#8ab815": "#4d7c0f"}

out = ["/* Generated by scripts/gen-lms-theme.py: do not edit by hand. */", ""]
out += ["/* ---------- LMS light theme ---------- */", ".lms-white {",
        "  --background: 0 0% 100%; --foreground: 222.2 47.4% 11.2%;",
        "  --card: 0 0% 100%; --card-foreground: 222.2 47.4% 11.2%;",
        "  --popover: 0 0% 100%; --popover-foreground: 222.2 47.4% 11.2%;",
        "  --muted: 210 40% 96.1%; --muted-foreground: 215.4 16.3% 46.9%;",
        "  --accent: 210 40% 96.1%; --accent-foreground: 222.2 47.4% 11.2%;",
        "  --border: 214.3 31.8% 91.4%; --input: 214.3 31.8% 91.4%;", "}"]
for h, v in TEXT_LIGHT.items():
    out.append(f'.lms-white [style*="color: {rgb(h)}"], .lms-white {tw("text", h)} {{ color: {v} !important; }}')

out += ["", "/* ---------- LMS dark theme (navy) ---------- */",
        f"html.lms-dark {{ background: {PAGE}; color-scheme: dark; }}", ".lms-dark {",
        "  --background: 225 60% 14%; --foreground: 226 100% 97%;",
        "  --card: 224 46% 15%; --card-foreground: 226 100% 97%;",
        "  --popover: 224 46% 15%; --popover-foreground: 226 100% 97%;",
        "  --muted: 224 36% 20%; --muted-foreground: 224 30% 74%;",
        "  --accent: 224 36% 22%; --accent-foreground: 226 100% 97%;",
        "  --border: 224 34% 25%; --input: 224 34% 25%;", "}",
        ".lms-dark h1, .lms-dark h2, .lms-dark h3, .lms-dark h4 { color: #eef2ff; }",
        ".lms-dark input::placeholder, .lms-dark textarea::placeholder { color: #7c88a8 !important; }",
        '.lms-dark [style*="background: rgba(255, 255, 255, 0.86)"] { background: rgba(11, 18, 48, 0.92) !important; }', ""]
out.append("/* surfaces */")
for h, v in BG_DARK.items():
    sel = [f'.lms-dark [style*="background: {rgb(h)}"]', f'.lms-dark [style*="background-color: {rgb(h)}"]',
           f".lms-dark {tw('bg', h)}", f".lms-dark {tw(HOVER_BG, h)}:hover"]
    out.append(", ".join(sel) + f" {{ background-color: {v} !important; }}")
out.append("/* text */")
for h, v in TEXT_DARK.items():
    sel = [f'.lms-dark [style*="color: {rgb(h)}"]', f".lms-dark {tw('text', h)}", f".lms-dark {tw(HOVER_TEXT, h)}:hover"]
    out.append(", ".join(sel) + f" {{ color: {v} !important; }}")
out.append("/* borders */")
for h, v in BORDER_DARK.items():
    sel = [f'.lms-dark [style*="solid {rgb(h)}"]', f'.lms-dark [style*="border-color: {rgb(h)}"]',
           f".lms-dark {tw('border', h)}", f".lms-dark {tw(HOVER_BORDER, h)}:hover"]
    out.append(", ".join(sel) + f" {{ border-color: {v} !important; }}")
out.append("/* Tailwind palette utilities used in the LMS */")
out += [".lms-dark .bg-white { background-color: %s !important; }" % SURFACE,
        ".lms-dark .bg-slate-50 { background-color: %s !important; }" % RAISED,
        ".lms-dark .bg-slate-100 { background-color: %s !important; }" % RAISED,
        ".lms-dark .text-slate-900 { color: #eef2ff !important; }",
        ".lms-dark .text-slate-800, .lms-dark .text-slate-700 { color: #d7def0 !important; }",
        ".lms-dark .text-slate-600, .lms-dark .text-slate-500 { color: #a9b4cf !important; }",
        ".lms-dark .border-slate-200, .lms-dark .border-slate-100 { border-color: %s !important; }" % BORDER]
out.append("/* navy text stays navy on lime buttons and on surfaces marked lms-keep-dark */")
keep = []
for h in LIME_SOLID:
    keep += [f'html.lms-dark [style*="background: {rgb(h)}"]', f'html.lms-dark [style*="background: {rgb(h)}"] *',
             f"html.lms-dark {tw('bg', h)}", f"html.lms-dark {tw('bg', h)} *"]
keep += ["html.lms-dark .lms-keep-dark"]
out.append(", ".join(keep) + " { color: #0b0b2c !important; }")
out += ["", "/* badges (Gamification.tsx): designed for the dark theme */",
    "html.lms-dark .lms-badge--earned { background: linear-gradient(180deg, rgba(158, 255, 31, 0.16), rgba(158, 255, 31, 0.04)) !important; border-color: rgba(158, 255, 31, 0.45) !important; }",
    "html.lms-dark .lms-badge--earned .lms-badge-icon { background: rgba(11, 18, 48, 0.65) !important; box-shadow: 0 0 0 1px rgba(158, 255, 31, 0.45), 0 0 18px rgba(158, 255, 31, 0.22) !important; }",
    "html.lms-dark .lms-badge--earned .lms-badge-name { color: #e6ffc2 !important; }",
    "html.lms-dark .lms-badge--locked { background: #121b3a !important; border-color: #222c52 !important; }",
    "html.lms-dark .lms-badge--locked .lms-badge-icon { background: #1a2448 !important; }",
    "html.lms-dark .lms-badge--locked .lms-badge-name { color: #8794b3 !important; }",
    "html.lms-dark .lms-badge-lock { background: #26325a !important; color: #a9b4cf !important; }"]
open("src/lms-theme.css", "w").write("\n".join(out) + "\n")
print("wrote src/lms-theme.css:", len(out), "lines")
